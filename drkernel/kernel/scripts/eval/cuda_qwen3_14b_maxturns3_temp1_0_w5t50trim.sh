MODEL_NAME="${MODEL_NAME:-Qwen3-14B}"
MODEL_PATH="${MODEL_PATH:-/nfs/FM/chenshuailin/checkpoints/Qwen/Qwen3-14B}"

MULTI_TURN="${MULTI_TURN:-True}"
MAX_USER_TURNS="${MAX_USER_TURNS:-3}"
PROMPT_CONFIG_PATH="${PROMPT_CONFIG_PATH:-kernel/config/prompt_config/multi_turn_cuda_kernel.yaml}"

GRADIO_VISUALIZATION="${GRADIO_VISUALIZATION:-False}"
