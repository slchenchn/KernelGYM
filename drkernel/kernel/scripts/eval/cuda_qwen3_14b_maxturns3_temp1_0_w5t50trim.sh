  mkdir -p "${RUN_DIR}"
  export DRKERNEL_EVAL_LOG_INITIALIZED=1
  exec > >(tee -a "${LOG_PATH}") 2>&1
fi

echo "Runtime Environment:"
echo "  which python: $(which python)"
python - <<'PY'
import os
import sys

print(f"  sys.executable: {sys.executable}")
print(f"  VIRTUAL_ENV: {os.environ.get('VIRTUAL_ENV')}")
PY

FSDP_SIZE="${FSDP_SIZE:--1}"
PROJECT_NAME="${PROJECT_NAME:-kernel-grading}"
EXPERIMENT_NAME="${EXPERIMENT_NAME:-${RUN_NAME}}"
TRAINER_LOGGER="${TRAINER_LOGGER:-[]}"

EVAL_DATASET="${EVAL_DATASET:-${DRKERNEL_ROOT}/data/drkernel-validation-data-neutral/validation_data_thinking.parquet}"
