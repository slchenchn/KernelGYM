#!/bin/bash
# Qwen3-14B CUDA offline grading.
# Produces checkpoint-eval-compatible outputs under .../eval_results/step_0.

export GLOO_SOCKET_IFNAME="${GLOO_SOCKET_IFNAME:-ens22f0}"
export NCCL_SOCKET_IFNAME="${NCCL_SOCKET_IFNAME:-ens22f0}"
export NCCL_NET="${NCCL_NET:-Socket}"
