N_SAMPLES="${N_SAMPLES:-8}"
BATCH_SIZE="${BATCH_SIZE:-128}"
TEMPERATURE="${TEMPERATURE:-1.0}"
TOP_P="${TOP_P:-1.0}"
TOP_K="${TOP_K:--1}"
MIN_P="${MIN_P:-0.0}"
DO_SAMPLE="${DO_SAMPLE:-True}"

ROLLOUT_MODE="${ROLLOUT_MODE:-standalone_vllm}"
ROLLOUT_GPU_MEMORY_UTIL="${ROLLOUT_GPU_MEMORY_UTIL:-0.75}"
ROLLOUT_TENSOR_MODEL_PARALLEL_SIZE="${ROLLOUT_TENSOR_MODEL_PARALLEL_SIZE:-2}"
ROLLOUT_MAX_NUM_SEQS="${ROLLOUT_MAX_NUM_SEQS:-512}"
ROLLOUT_DISABLE_LOG_STATS="${ROLLOUT_DISABLE_LOG_STATS:-False}"
VLLM_LANGUAGE_MODEL_ONLY="${VLLM_LANGUAGE_MODEL_ONLY:-true}"

SOLVE_THRESHOLD="${SOLVE_THRESHOLD:-0.99}"
PASS_AT_K="${PASS_AT_K:-1}"

REWARD_SERVER_URL="${REWARD_SERVER_URL:-${KERNELGYM_SERVER_URL:-http://192.168.16.39:8111}}"
REWARD_MANAGER="${REWARD_MANAGER:-kernel_async}"
REWARD_FUNC_NAME="${REWARD_FUNC_NAME:-calculate_reward_speedup}"
REWARD_WEIGHTS="${REWARD_WEIGHTS:-0.3_0.4_0.3}"
REFERENCE_BACKEND="${REFERENCE_BACKEND:-pytorch}"
KERNEL_BACKEND="${KERNEL_BACKEND:-cuda_agent}"
DETECT_DECOY_KERNEL="${DETECT_DECOY_KERNEL:-true}"
COVERAGE_REWARD_TYPE="${COVERAGE_REWARD_TYPE:-time_coverage}"
COVERAGE_REWARD_ENABLE="${COVERAGE_REWARD_ENABLE:-False}"
COVERAGE_REWARD_WEIGHT="${COVERAGE_REWARD_WEIGHT:-0.25}"

REWARD_ENHANCED="${REWARD_ENHANCED:-True}"
REWARD_USE_SANDBOX_RATE_LIMIT="${REWARD_USE_SANDBOX_RATE_LIMIT:-True}"
REWARD_RATE_LIMIT="${REWARD_RATE_LIMIT:-64}"
REWARD_ACQUIRE_TIMEOUT="${REWARD_ACQUIRE_TIMEOUT:-2400}"
REWARD_MAX_CONCURRENT="${REWARD_MAX_CONCURRENT:-64}"
REWARD_TIMEOUT="${REWARD_TIMEOUT:-2400}"
REWARD_MAX_RETRIES="${REWARD_MAX_RETRIES:-3}"
